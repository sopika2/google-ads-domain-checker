// Regenerates src/regions.ts from the i18n-iso-countries dataset (dev dependency).
// Usage: npm run generate:regions
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const countries = require('i18n-iso-countries');
const en = require('i18n-iso-countries/langs/en.json');
countries.registerLocale(en);

const alpha2ToNumeric = countries.getNumericCodes(); // { '004': 'AF', ... }
const entries = Object.entries(alpha2ToNumeric)
    .map(([numeric, alpha2]) => [alpha2, Number.parseInt(numeric, 10)])
    .filter(([alpha2, numeric]) => /^[A-Z]{2}$/.test(alpha2) && Number.isInteger(numeric))
    .sort((a, b) => a[0].localeCompare(b[0]));

const names = {};
for (const [alpha2] of entries) names[alpha2] = countries.getName(alpha2, 'en', { select: 'official' }) ?? alpha2;

const lines = [];
lines.push('/**');
lines.push(' * ISO 3166-1 alpha-2 -> numeric codes. GENERATED by scripts/generate-regions.mjs from i18n-iso-countries;');
lines.push(' * do not edit by hand. The Ads Transparency Center region id is 2000 + the numeric code (US = 2840, HU = 2348).');
lines.push(' */');
lines.push('');
lines.push('export const ISO_NUMERIC_BY_ALPHA2: Readonly<Record<string, number>> = Object.freeze({');
for (const [alpha2, numeric] of entries) lines.push(`    ${alpha2}: ${numeric}, // ${names[alpha2]}`);
lines.push('});');
lines.push('');
lines.push(`export const REGION_COUNT = ${entries.length};`);
lines.push('');

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'src', 'regions-data.ts');
const next = lines.join('\n');
let prev = '';
try { prev = readFileSync(target, 'utf8'); } catch {}
if (prev !== next) {
    writeFileSync(target, next);
    console.log(`Wrote ${target} with ${entries.length} regions`);
} else {
    console.log(`${target} is up to date (${entries.length} regions)`);
}
